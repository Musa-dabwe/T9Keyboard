    fun search(query: String): List<String> {
        if (query.isBlank()) return emptyList()
        val words = query.lowercase().trim().split(Regex("\\s+"))
        return keywords.entries
            .filter { (_, kws) ->
                words.all { word -> kws.any { it.contains(word) } }
            }
            .map { it.key }
    }
